    fn source_filled_state_counts(record_id: &str) -> (i64, i64, i64) {
        let (source_rows, fences, versions) = Spi::get_three_with_args::<i64, i64, i64>(
            "SELECT (
                 SELECT count(*)
                 FROM public.test_source_filled_items
                 WHERE id = $1::uuid
             ), (
                 SELECT count(*)
                 FROM synchro.sync_write_fences fence
                 JOIN synchro.sync_registry registry
                   ON registry.relation_id = fence.relation_id
                 JOIN synchro.sync_registry_generations generation
                   ON generation.generation = registry.registry_generation
                 WHERE generation.state = 'active'
                   AND registry.table_name = 'test_source_filled_items'
                   AND $1 IN (fence.old_record_id, fence.new_record_id)
             ), (
                 SELECT count(*)
                 FROM synchro.sync_row_versions version
                 JOIN synchro.sync_registry registry
                   ON registry.relation_id = version.relation_id
                 JOIN synchro.sync_registry_generations generation
                   ON generation.generation = registry.registry_generation
                 WHERE generation.state = 'active'
                   AND registry.table_name = 'test_source_filled_items'
                   AND version.record_id = $1
             )",
            &[record_id.into()],
        )
        .expect("read source-filled rejected write state");
        (
            source_rows.expect("source-filled source count"),
            fences.expect("source-filled fence count"),
            versions.expect("source-filled row-version count"),
        )
    }

    fn assert_last_fence_matches_outcome(
        table_name: &str,
        record_id: &str,
        mutation_id: &str,
        outcome: &Value,
    ) {
        let state: pgrx::JsonB = Spi::get_one_with_args(
            "SELECT jsonb_build_object(
                 'count', count(*),
                 'last_version',
                 (array_agg(row_version::text ORDER BY dml_ordinal DESC))[1]
             )
             FROM synchro.sync_write_fences fence
             JOIN synchro.sync_registry registry
               ON registry.relation_id = fence.relation_id
             JOIN synchro.sync_registry_generations generation
               ON generation.generation = registry.registry_generation
             WHERE generation.state = 'active'
               AND registry.table_name = $1
               AND fence.mutation_id = $2
               AND $3 IN (fence.old_record_id, fence.new_record_id)",
            &[table_name.into(), mutation_id.into(), record_id.into()],
        )
        .expect("read source-write fences")
        .expect("source-write fence state");
        let count = state.0["count"].as_i64().expect("source-write fence count");
        let last_version = state.0["last_version"]
            .as_str()
            .expect("source-write last fence version");
        assert!(count > 1);
        assert_eq!(outcome["server_version"].as_str(), Some(last_version));
        assert_eq!(current_row_version(table_name, record_id), last_version);
    }

