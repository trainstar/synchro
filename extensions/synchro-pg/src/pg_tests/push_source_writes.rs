    fn current_fence_version(
        table_name: &str,
        record_id: &str,
        mutation: &synchro_core::contract::Mutation,
    ) -> Option<crate::push::UnitEndFence> {
        Spi::connect(|client| {
            let registration = crate::registry::load_registry_from_client(client)?
                .into_iter()
                .find(|registration| registration.table_name == table_name)
                .expect("source-write table registration");
            Ok::<_, pgrx::spi::Error>(crate::push::load_current_fence_version(
                client,
                mutation,
                &registration,
                record_id,
            ))
        })
        .expect("read source-write fence version")
    }

