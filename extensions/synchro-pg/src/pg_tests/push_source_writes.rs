    fn push_insert_missing_required_value_rejects_terminal_and_replays() {
        setup_source_filled_items();
        let user_id = "source-filled-user";
        let client_id = "source-filled-client";
        let record_id = "91000000-0000-4000-8000-000000000002";
        register_client(user_id, client_id);
        let request = push_request(
            user_id,
            client_id,
            "source-filled-missing-value",
            vec![push_mutation(
                (user_id, client_id),
                "source-filled-missing-value",
                "test_source_filled_items",
                "insert",
                record_id,
                None,
                Some(&[("owner_id", json!(user_id))]),
            )],
        );
        let prior_sequence_value = source_filled_next_sequence_value();

        let first = execute_push(user_id, &request);

        assert_eq!(first.json["rejected"][0]["status"], "rejected_terminal");
        assert_eq!(
            first.json["rejected"][0]["code"].as_str(),
            Some("validation_failed")
        );
        assert_eq!(source_filled_state_counts(record_id), (0, 0, 0));
        assert_eq!(
            source_filled_next_sequence_value(),
            prior_sequence_value + 2,
            "the physical insert must evaluate the identity default before it fails"
        );

        let replay = execute_push(user_id, &request);
        assert_eq!(replay.raw, first.raw);
    }

